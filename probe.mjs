const W = 'https://site.web.api.espn.com/apis/common/v3/sports/football/college-football';
const B = 'https://site.api.espn.com/apis/site/v2/sports/football/college-football';
const get = async u => { const r = await fetch(u); return { ok: r.ok, status: r.status, d: r.ok ? await r.json() : null }; };
let r = await get(`${W}/statistics/byteam?region=us&lang=en&contentorigin=espn&limit=200`);
console.log('byteam:', r.status, '| teams:', r.d?.teams?.length, '| cats:', (r.d?.teams?.[0]?.categories || []).map(c => c.name).join(','));
console.log('byteam sample stats:', JSON.stringify((r.d?.teams?.[0]?.categories || []).slice(0,2)).slice(0, 500));
r = await get(`${W}/statistics/byathlete?region=us&lang=en&contentorigin=espn&isqualified=false&limit=50`);
console.log('byathlete:', r.status, '| athletes:', r.d?.athletes?.length, '| cats:', (r.d?.athletes?.[0]?.categories || []).map(c => c.name).join(','));
r = await get(`${B}/injuries`);
console.log('injuries:', r.status, '| teams:', (r.d?.injuries || []).length, '| first:', JSON.stringify((r.d?.injuries || [])[0] || null).slice(0, 220));
r = await get(`${B}/teams/61/schedule`);
console.log('schedule:', r.status, '| events:', (r.d?.events || []).length);
r = await get(`${B}/teams/61/roster`);
console.log('roster:', r.status, '| athletes:', (r.d?.athletes || []).length, Array.isArray(r.d?.athletes) ? typeof r.d.athletes[0] : '');
