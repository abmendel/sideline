import zlib from 'node:zlib';
const B = 'https://site.api.espn.com/apis/site/v2/sports/football/college-football';
const get = async u => { const r = await fetch(u); return r.ok ? await r.json() : null; };
const out = {};
out.scoreboard = await get(`${B}/scoreboard?groups=80&limit=200`);
const ev = (out.scoreboard?.events || [])[0];
out.summary = ev ? await get(`${B}/summary?event=${ev.id}`) : null;
out.standings = await get('https://site.api.espn.com/apis/v2/sports/football/college-football/standings?level=3');
out.rankings = await get(`${B}/rankings`);
out.news = await get(`${B}/news?limit=12`);
const t = (out.scoreboard?.events?.[0]?.competitions?.[0]?.competitors?.[0]?.team?.id);
out.schedule = t ? await get(`${B}/teams/${t}/schedule`) : null;
out.teamId = t;
const buf = zlib.gzipSync(Buffer.from(JSON.stringify(out)));
const b64 = buf.toString('base64');
console.log('FIXSTART', b64.length);
for (let i = 0; i < b64.length; i += 4000) console.log('FIX' + b64.slice(i, i + 4000));
console.log('FIXEND');
