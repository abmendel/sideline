import zlib from 'node:zlib';
const W = 'https://site.web.api.espn.com/apis/common/v3/sports/football/college-football';
const B = 'https://site.api.espn.com/apis/site/v2/sports/football/college-football';
const get = async u => { const r = await fetch(u); return r.ok ? await r.json() : null; };
const out = {};
out.byteam = await get(`${W}/statistics/byteam?region=us&lang=en&contentorigin=espn&limit=200`);
out.injuries = await get(`${B}/injuries`);
out.roster = await get(`${B}/teams/61/roster`);
out.byathlete = await get(`${W}/statistics/byathlete?region=us&lang=en&contentorigin=espn&isqualified=false&limit=50`);
const b64 = zlib.gzipSync(Buffer.from(JSON.stringify(out))).toString('base64');
console.log('FIXSTART', b64.length);
for (let i = 0; i < b64.length; i += 4000) console.log('FIX' + b64.slice(i, i + 4000));
console.log('FIXEND');
